// Jev as a TAGGER (Fable #12): situation, formality, audience, data-hygiene flags, plus the closure probe ("is this AI").
// Reads a decrypted temp file (path in argv[2]) inside the runner; writes answers (ids + numbers/labels, no text) to argv[3].
// Logs print counts and token usage only, never text.
import fs from 'node:fs';
import { TypeSafeClient, choice, noul, score } from '@typesafe-ai/sdk';
const client = new TypeSafeClient({ apiKey: process.env.JEV_API_KEY.trim(), timeout: 60000 });
const Q = {
  situation: choice('What kind of text is this?', { notice: null, letter: null, question: null, answer_explanation: null, advice: null,
    opinion: null, personal_story: null, news_report: null, marketing: null, chat_message: null, speech: null, encyclopedic: null, instructions: null }),
  formality: score('How formal is the language?', ['very informal', 'informal', 'neutral', 'formal', 'very formal']),
  known_group: noul('The text addresses a specific group of people the writer knows (members of a group, class, team, family).'),
  general_reader: noul('The text addresses an unknown general reader.'),
  machine_translated: noul('The text reads like an automatic machine translation into Hebrew.'),
  garbled: noul('The text is garbled, broken or boilerplate (menus, link lists, cut-off fragments).'),
  not_hebrew: noul('Most of the text is not in Hebrew.'),
  refusal_or_clarification: noul('The text refuses a request or asks the user to clarify or complete a cut-off question.'),
  ai: noul('This Hebrew text was generated by an AI model (such as ChatGPT, Claude or Gemini) rather than written by a person.'),
  chatbot_tone: noul('The text is polished, balanced and hedged, organized the way a chatbot answers (overview, considerations, recommendation).'),
};
const rows = fs.readFileSync(process.argv[2], 'utf8').split('\n').filter(Boolean).map(JSON.parse);
const out = fs.createWriteStream(process.argv[3]);
const MAXTOK = Number(process.env.MAX_INPUT_TOKENS || 40e6);   // hard budget guard
let done = 0, fail = 0, inTok = 0; const t0 = Date.now(); let i = 0;
async function one(r) {
  for (let k = 0; k < 4; k++) {
    try {
      const res = await client.systemOne({ model: 'jev-latest', state: r.text, questions: Q });
      inTok += res.usage?.input_tokens || 0;
      const a = {}; for (const [q, v] of Object.entries(res.answers)) a[q] = v.noul ?? v.choice ?? v.score ?? null;
      out.write(JSON.stringify({ id: r.id, model: res.model, tok: res.usage?.input_tokens || 0, ...a }) + '\n');
      return;
    } catch (e) { if (k === 3) { fail++; console.log('fail', r.id, String(e).slice(0, 120)); } else await new Promise(s => setTimeout(s, 2000 * (k + 1))); }
  }
}
await Promise.all(Array.from({ length: 8 }, async () => {
  while (i < rows.length && inTok < MAXTOK) { const r = rows[i++]; await one(r); if (++done % 100 === 0) console.log(done, '/', rows.length, 'fail', fail, 'input tokens', inTok); }
}));
out.end();
console.log(`::notice::done ${done} fail ${fail} input tokens ${inTok} (${((Date.now() - t0) / 1000).toFixed(0)}s)`);
